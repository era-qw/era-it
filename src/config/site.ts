/** Ссылка на WhatsApp с предзаполненным текстом сообщения. */
export function whatsappLink(message: string): string {
  const base = contacts.WHATSAPP_URL
  return `${base}${base.includes('?') ? '&' : '?'}text=${encodeURIComponent(message)}`
}

